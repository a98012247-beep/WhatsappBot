// Generates lib/menu-data.js (ESM) from sections.js + web descriptions.
// Run: node tools/build-menu-data.mjs   (cwd: ~/workspace/whatsapp-bot)
import { readFileSync, writeFileSync } from 'fs';
const PUB = '/home/hatch/workspace/whatsapp-bot/src/exe/public/';
const R = (p) => readFileSync(PUB + p, 'utf8');

const window = {};
eval(R('extra-cmds/sections.js'));
const sections = window.COMMAND_SECTIONS;

// primary command names: function-valued HANDLERS entries (batches 1-7).
// Anything NOT listed as a string-valued alias in batch HANDLERS counts as
// primary — this keeps the original bot.js switch commands (sections 1-9)
// visible too, instead of marking them all primary:false.
const primaries = new Set();
const aliases = new Set();
const aliasToCanonical = {};
for (const f of ['batch1-fun-ai.js','batch2-media-tools.js','batch3-deen-edu.js','batch4-groups-auto.js','batch5-biz-money.js','batch6-health-news.js','batch7-more.js','batch8-newcmds.js','batch8b-media.js','batch8c-group.js','batch8d-fun.js']) {
  const mod = await import('/home/hatch/workspace/whatsapp-bot/src/exe/lib/' + f);
  for (const [k, v] of Object.entries(mod.HANDLERS || {})) {
    if (typeof v === 'function') primaries.add(k.toLowerCase());
    else if (typeof v === 'string') { aliases.add(k.toLowerCase()); aliasToCanonical[k.toLowerCase()] = v.toLowerCase(); }
  }
}
// CORE_ALIASES from batch8 (e.g. ban -> kick)
try {
  const b8 = await import('/home/hatch/workspace/whatsapp-bot/src/exe/lib/batch8-newcmds.js');
  for (const [k, v] of Object.entries(b8.CORE_ALIASES || {})) {
    aliases.add(k.toLowerCase()); aliasToCanonical[k.toLowerCase()] = String(v).toLowerCase();
  }
} catch {}
const isPrimary = (n) => !aliases.has(n.toLowerCase());
// Resolve alias -> canonical (one level; no chains observed)
const canonical = (n) => { n = n.toLowerCase(); return aliasToCanonical[n] || n; };

// name -> desc from all web sources (first wins)
const desc = {};
const put = (name, d) => { name = name.toLowerCase(); if (!desc[name] && d) desc[name] = d.trim(); };
for (const m of R('index.html').matchAll(/<button class="cmd"><code>!([^<\s\/·|]+)[^<]*<\/code><span>([^<]*)<\/span>/g)) put(m[1], m[2]);
for (const m of R('extra-cmds/batch1.js').matchAll(/\['!([a-z0-9_]+)[^']*',\s*'([^']*)'\]/gi)) put(m[1], m[2]);
for (const m of R('extra-cmds/batch2.js').matchAll(/cmd:\s*'!([a-z0-9_]+)[^']*',\s*desc:\s*'([^']*)'/gi)) put(m[1], m[2]);
for (const m of R('extra-cmds/batch3.js').matchAll(/usage:\s*'([a-z0-9_]+)[^']*',\s*desc:\s*'([^']*)'/gi)) put(m[1], m[2]);
for (const m of R('extra-cmds/batch5.js').matchAll(/cmd:\s*'([a-z0-9_]+)',\s*example:[^,]+,\s*desc:\s*'([^']*)'/gi)) put(m[1], m[2]);
for (const m of R('extra-cmds/batch6.js').matchAll(/code:\s*'!([a-z0-9_]+)[^']*',\s*desc:\s*'([^']*)'/gi)) put(m[1], m[2]);
for (const m of R('extra-cmds/batch7.js').matchAll(/cmd:\s*'!([a-z0-9_]+)[^']*',\s*desc:\s*'([^']*)'/gi)) put(m[1], m[2]);
for (const m of R('extra-cmds/batch8.js').matchAll(/cmd:\s*'!([a-z0-9_]+)[^']*',\s*desc:\s*'([^']*)'/gi)) put(m[1], m[2]);

const cats = sections.map(s => {
  // DEDUP (2026-10-15): one command per function — resolve aliases to their
  // canonical name and keep only the first occurrence per category.
  const seen = new Set();
  const cmds = [];
  for (const n of s.cmds) {
    const c = canonical(n);
    if (seen.has(c)) continue;
    seen.add(c);
    cmds.push({ name: c, desc: desc[c] || desc[n.toLowerCase()] || '', primary: isPrimary(c) });
  }
  return { num: s.num, icon: s.icon, title: s.title, cmds };
});
const js = `// AUTO-GENERATED by tools/build-menu-data.mjs — do not hand-edit.\n// Regenerate after adding batches.\nexport const MENU_CATEGORIES = ${JSON.stringify(cats, null, 1)};\n`;
writeFileSync('/home/hatch/workspace/whatsapp-bot/src/exe/lib/menu-data.js', js);
console.log('categories:', cats.length, '| commands:', cats.reduce((n, c) => n + c.cmds.length, 0));
